import { validateApplicationInput } from '../../src/logic/it-1-br-2-1-1';

describe("申請書類の文書種別を自動判別し補助金関連度に基づいて電子化可否を判定する機能", () => {
  test("申請内容の必須項目が全て適切に入力されている場合、妥当と判定し次の処理に進める", () => {
    // SCEN-417
    
    // 必須項目が全て適切に入力されている場合
    const result = validateApplicationInput(
      "科学研究費助成事業の申請について",
      "本申請は、科学技術の発展に寄与する研究プロジェクトの実施に必要な予算の確保を目的としており、具体的な研究計画と予算詳細を記載しています。",
      "補助金申請",
      "学術研究推進部",
      "通常"
    );
    
    expect(result).toEqual({
      isValid: true,
      errors: [],
      warnings: []
    });
    
    // 境界値テスト: タイトルが10文字ちょうど
    const boundaryResult = validateApplicationInput(
      "研究費申請書類について",
      "この申請書類は研究活動に必要な費用の申請を行うものであり、詳細な研究計画と予算配分について記載している文書です。",
      "補助金申請", 
      "研究推進課",
      "急ぎ"
    );
    
    expect(boundaryResult).toEqual({
      isValid: true,
      errors: [],
      warnings: []
    });
    
    // エラーケース: タイトルが空
    expect(() => {
      validateApplicationInput(
        "",
        "申請内容の詳細をここに記載します。この内容は50文字以上で詳しく記載する必要があります。",
        "補助金申請",
        "学術研究推進部", 
        "通常"
      );
    }).toThrow("申請書類のタイトルは必須項目です。入力してください。");
    
    // エラーケース: 申請内容が50文字未満
    expect(() => {
      validateApplicationInput(
        "研究費申請書類について",
        "短い内容",
        "補助金申請",
        "学術研究推進部",
        "通常" 
      );
    }).toThrow("申請内容は50文字以上で詳しく記載してください。");
    
    // エラーケース: 申請種別が未選択
    expect(() => {
      validateApplicationInput(
        "研究費申請書類について", 
        "この申請書類は研究活動に必要な費用の申請を行うものであり、詳細な研究計画と予算配分について記載している文書です。",
        "",
        "学術研究推進部",
        "通常"
      );
    }).toThrow("申請種別を選択してください。");
    
    // エラーケース: 所属部署が未入力
    expect(() => {
      validateApplicationInput(
        "研究費申請書類について",
        "この申請書類は研究活動に必要な費用の申請を行うものであり、詳細な研究計画と予算配分について記載している文書です。", 
        "補助金申請",
        "",
        "通常"
      );
    }).toThrow("所属部署を入力してください。");
  });
});