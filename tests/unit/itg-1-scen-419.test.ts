import { validateApplicationInput } from "../../src/logic/it-1-br-2-1-1";

describe("申請書類の文書種別を自動判別し補助金関連度に基づいて電子化可否を判定する機能", () => {
  test("必須項目の境界値での入力時、適切に検証される", () => {
    // SCEN-419

    // 正常ケース: 全項目が境界値ちょうどで有効
    expect(validateApplicationInput(
      "1234567890", // 10文字ちょうど（最小）
      "12345678901234567890123456789012345678901234567890", // 50文字ちょうど（最小）
      "補助金申請",
      "総務課",
      "通常"
    )).toEqual({
      isValid: true,
      errors: [],
      warnings: []
    });

    expect(validateApplicationInput(
      "12345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890", // 200文字ちょうど（最大）
      "12345678901234567890123456789012345678901234567890", // 50文字ちょうど（最小）
      "補助金申請",
      "総務課",
      "通常"
    )).toEqual({
      isValid: true,
      errors: [],
      warnings: []
    });

    // 境界値エラーケース: タイトル9文字（境界値未満）
    expect(() => validateApplicationInput(
      "123456789", // 9文字
      "12345678901234567890123456789012345678901234567890",
      "補助金申請",
      "総務課",
      "通常"
    )).toThrow("申請書類のタイトルは10文字以上200文字以内で入力してください");

    // 境界値エラーケース: タイトル201文字（境界値超過）
    expect(() => validateApplicationInput(
      "123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901234567890123456789012345678901", // 201文字
      "12345678901234567890123456789012345678901234567890",
      "補助金申請",
      "総務課",
      "通常"
    )).toThrow("申請書類のタイトルは10文字以上200文字以内で入力してください");

    // 境界値エラーケース: 内容49文字（境界値未満）
    expect(() => validateApplicationInput(
      "1234567890",
      "1234567890123456789012345678901234567890123456789", // 49文字
      "補助金申請",
      "総務課",
      "通常"
    )).toThrow("申請内容は50文字以上で詳しく記載してください。");

    // 必須項目欠損エラーケース
    expect(() => validateApplicationInput(
      "", // 空文字
      "12345678901234567890123456789012345678901234567890",
      "補助金申請",
      "総務課",
      "通常"
    )).toThrow("申請書類のタイトルは必須項目です。入力してください。");

    expect(() => validateApplicationInput(
      "1234567890",
      "", // 空文字
      "補助金申請",
      "総務課",
      "通常"
    )).toThrow("申請内容は50文字以上で詳しく記載してください。");

    expect(() => validateApplicationInput(
      "1234567890",
      "12345678901234567890123456789012345678901234567890",
      "", // 空文字
      "総務課",
      "通常"
    )).toThrow("申請種別を選択してください。");

    expect(() => validateApplicationInput(
      "1234567890",
      "12345678901234567890123456789012345678901234567890",
      "補助金申請",
      "", // 空文字
      "通常"
    )).toThrow("所属部署を入力してください。");
  });
});